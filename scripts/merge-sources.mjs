#!/usr/bin/env node
/**
 * Regenerate src/data/sources.ts from research/*.sources.json.
 * Only sources actually referenced (`source: "id"`) in src/data/** are kept,
 * so the bibliography never drifts from the pages. Idempotent.
 * Usage: node scripts/merge-sources.mjs
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const RESEARCH = join(ROOT, "research");
const OUT = join(ROOT, "src/data/sources.ts");
const SRC = join(ROOT, "src");

// 1. collect used ids
const used = new Map(); // id -> where
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(f)) {
      const txt = readFileSync(p, "utf8");
      for (const m of txt.matchAll(/source:\s*["']([^"']+)["']/g)) {
        for (const id of m[1].split(";").map((s) => s.trim()).filter(Boolean)) {
          if (!used.has(id)) used.set(id, relative(ROOT, p));
        }
      }
    }
  }
};
walk(join(SRC, "data"));

// 2. load packs
const packs = new Map();
for (const f of readdirSync(RESEARCH).filter((x) => x.endsWith(".sources.json"))) {
  for (const s of JSON.parse(readFileSync(join(RESEARCH, f), "utf8"))) {
    if (!packs.has(s.id)) packs.set(s.id, s);
  }
}

// 3. emit cited sources, sorted; report orphans without dropping the pack data
const esc = (t) => String(t).replace(/\\/g, "\\\\").replace(/'/g, "\\'");
const cited = [...used.keys()].sort();
const entries = [];
const missing = [];
for (const id of cited) {
  const s = packs.get(id);
  if (!s) { missing.push(id); continue; }
  entries.push(
    `  "${id}": {\n    title: '${esc(s.title)}',\n    publisher: '${esc(s.publisher)}',\n    year: ${s.year},\n    url: '${esc(s.url)}',\n  },`,
  );
}
const unused = [...packs.keys()].filter((id) => !used.has(id));

const out = `/**
 * Central bibliography — GENERATED by scripts/merge-sources.mjs from
 * research/*.sources.json. Do not hand-edit; the packs are the source of truth.
 * Only sources cited on the pages are included.
 */
export type Source = {
  title: string;
  publisher: string;
  year: number;
  url: string;
};

export const SOURCES: Record<string, Source> = {
${entries.join("\n\n")}
};
`;
writeFileSync(OUT, out);
console.log(`sources: ${entries.length} cited, ${unused.length} pack sources not yet cited (kept in packs)`);
if (missing.length) {
  console.error(`MISSING from packs: ${missing.join(", ")}`);
  process.exit(1);
}
